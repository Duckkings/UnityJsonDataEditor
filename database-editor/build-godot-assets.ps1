$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$assetRoot = Join-Path $repoRoot 'Runtime/GodotProject'
$manifest = Get-Content -LiteralPath (Join-Path $assetRoot 'manifest.json') -Raw | ConvertFrom-Json
$assets = [ordered]@{}
foreach ($entry in $manifest.files) {
  $path = Join-Path $assetRoot $entry.path
  if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant() -ne $entry.sha256) {
    throw "Godot asset differs from sync manifest: $($entry.path). Run sync-pas-runtime.ps1 to update the snapshot."
  }
  $assets[$entry.path] = [IO.File]::ReadAllText($path)
}
$json = ConvertTo-Json -InputObject $assets -Depth 5 -Compress
$module = "// Generated by build-godot-assets.ps1 from Runtime/GodotProject. Do not edit.`nexport const godotProjectAssets = $json;`nexport function getGodotProjectAsset(path) {`n  if (!Object.hasOwn(godotProjectAssets, path)) throw new Error('Missing Godot project asset: ' + path);`n  return godotProjectAssets[path];`n}`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'src/generators/godot-project-assets.js'), $module, [Text.UTF8Encoding]::new($false))
